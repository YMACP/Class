import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const slug = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const safePath = value => typeof value === 'string' && value.length <= 500 && !value.includes('\\') && !value.includes('\0') && !path.posix.isAbsolute(value) && value.split('/').every(part => part && part !== '.' && part !== '..' && !part.includes(':'));

// Build from the reviewed, pinned local snapshot only. Builds never fetch skills,
// run helper scripts or depend on files beside the distributed executable.
export function embedSkills() {
  const directory = path.join(root, 'assets', 'builtin-skills');
  const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8'));
  if (manifest.version !== 1 || !Array.isArray(manifest.sources) || !Array.isArray(manifest.skills)) throw Error('Invalid built-in Skill manifest');
  const sources = new Map(manifest.sources.map(source => [source.id, source]));
  if (sources.size !== manifest.sources.length) throw Error('Duplicate Skill source');
  const catalogue = [], files = Object.create(null), ids = new Set();
  let bytes = 0;
  const decoder = new TextDecoder('utf-8', { fatal: true });
  for (const skill of manifest.skills) {
    const source = sources.get(skill.source);
    if (!slug.test(skill.id) || !slug.test(skill.source) || ids.has(skill.id) || !source || !/^[a-f0-9]{40}$/.test(source.commit)) throw Error('Invalid built-in Skill identity');
    if (!Array.isArray(skill.files) || !skill.files.includes('SKILL.md') || new Set(skill.files).size !== skill.files.length) throw Error('Invalid built-in Skill files');
    ids.add(skill.id);
    const hashes = Object.create(null);
    for (const relative of skill.files) {
      if (!safePath(relative) || /(?:^|\/)(?:LICENSE(?:\..*)?|install_ctf_tools\.sh)$/i.test(relative)) throw Error('Disallowed built-in Skill file: ' + relative);
      const filename = path.join(directory, skill.source, skill.id, ...relative.split('/'));
      const stat = fs.lstatSync(filename), actual = fs.realpathSync(filename), base = fs.realpathSync(directory);
      if (!stat.isFile() || !actual.startsWith(base + path.sep)) throw Error('Skill resource must be a regular contained file');
      const buffer = fs.readFileSync(filename);
      if (buffer.length > 2 * 1024 * 1024) throw Error('Skill resource exceeds size limit');
      bytes += buffer.length;
      if (bytes > 10 * 1024 * 1024) throw Error('Built-in Skills exceed size budget');
      const content = decoder.decode(buffer);
      if (content.includes('\0')) throw Error('Only text Skill resources are supported');
      files[`${skill.source}/${skill.id}/${relative}`] = content;
      hashes[relative] = createHash('sha256').update(buffer).digest('hex');
    }
    catalogue.push({ ...skill, repository: source.repository, commit: source.commit, license: source.license, hashes });
  }
  const target = path.join(root, 'build', 'generated', 'builtin-skills.generated.js');
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const content = '// Generated by scripts/embed-skills.js from assets/builtin-skills/. Do not edit.\n'
    + 'export const BUILTIN_SKILL_CATALOGUE = ' + JSON.stringify(catalogue) + ';\n'
    + 'export const BUILTIN_SKILL_FILES = ' + JSON.stringify(files) + ';\n';
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
    const temporary = `${target}.${process.pid}.tmp`;
    fs.writeFileSync(temporary, content, 'utf8');
    fs.renameSync(temporary, target);
  }
  return { file: target, skills: catalogue.length, resources: Object.keys(files).length, bytes };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(JSON.stringify(embedSkills()));
